function [D,raw_D,uniform_mm,H_flat,metadata]=prepare_positive_corrosion_surface(Z190,cfg)
% 190 mm统一齐平矩阵 -> 同坐标系中央段 -> 正向深度；不取绝对值。
if nargin<2 || isempty(cfg),cfg=step00_corrosion_config();end
assert(ismatrix(Z190)&&all(isfinite(Z190(:))), ...
    'reference:InvalidSurface','请传入完整补齐的190 mm矩阵。');
% 第1步：沿用原参考区和范围20%高度定义；返回中央段列号。
[~,H_flat,~,columns]=jisuan_190(Z190,cfg);
% 第2步：只减同一个参考高度；向内增大的高度对应正腐蚀深度。
raw_D=Z190(:,columns)-H_flat;
% 第3步：仅平滑中央段一次，与模拟评价器保持同样的高斯边界规则。
assert(isscalar(cfg.preprocessing.main_gaussian_sigma)&& ...
    isfinite(cfg.preprocessing.main_gaussian_sigma)&&cfg.preprocessing.main_gaussian_sigma>=0, ...
    'reference:Sigma','主平滑sigma必须为非负有限标量。');
if cfg.preprocessing.main_gaussian_sigma>0
    D=imgaussfilt(raw_D,cfg.preprocessing.main_gaussian_sigma);
else
    D=raw_D;
end
% 第4步：最浅点为均匀分量；其余起伏为不均匀分量，不隐藏负值。
uniform_mm=min(D(:));
metadata=struct('crop_columns',columns,'reference_height_mm',H_flat, ...
    'raw_uniform_mm',min(raw_D(:)),'uniform_mm',uniform_mm, ...
    'grid_resolution_mm',cfg.preprocessing.grid_resolution_mm, ...
    'x_span_mm',(size(D,2)-1)*cfg.preprocessing.grid_resolution_mm, ...
    'y_span_mm',(size(D,1)-1)*cfg.preprocessing.grid_resolution_mm, ...
    'coordinate_frame','one aligned 190 mm scan', ...
    'depth_formula','D=Z190_central-H_flat; inward positive');
end
