% 
% #### 4. 平坦的地方垒一道矮墙（自适应梯度修正）
% 
% 在特别平的地方，人为把 “坡度” 拉高，相当于垒一道矮墙。
% **为什么这么做：** 平地水容易漫过去，本来是一个坑，会被水流拆成好几个。垒上墙之后，水漫不过去，小起伏都会被算进同一个大坑里，分出来的坑更完整。
% 
