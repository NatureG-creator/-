% **为什么这么做：** 边缘的坑不完整，分出来也没意义，还容易把整体分得乱七八糟。
% 参数 `yuzhi` 就是控制圈多大的荒地：数越大，圈的荒地越多，中间参与划分的有效区域越小。
% 
% #### 6. 保证旗子一定插在最低处（强制梯度极小值）
% 
% 在所有插旗子的地方、还有圈出来的荒地上，强制设成坡度最小的点。
% **为什么这么做：** 保证倒水的时候，水一定先积在旗子的位置，再慢慢往上涨。不会在别的平地上莫名其妙积出水来，彻底避免乱分坑。
% 
% #### 7. 开始慢慢灌水，自动分出坑（分水岭分割）
% 
% 往整个表面慢慢倒水，水位一点点往上涨：
% 
% - 每个坑底先积水，水面慢慢扩大；
% - 两个坑的水快要碰到一起时，就停住，中间形成一道分界线；
% - 最后给每个坑编上号，所有分界线统一记下来。
% 
% #### 8. 把每个坑的轮廓描出来（边界提取）
% 
% 挨个找到每个编号的坑，把它的外圈轮廓线描出来，再记下轮廓线上每个点的高度。
% **为什么这么做：** 后面算坑的深度、面积、体积，全靠这个轮廓线来算。
% 
% #### 9. 把所有分界线拼成一张图（全局边界）
% 
% 把所有坑的分界线拼在一起，做成一张黑白图，一眼就能看到所有坑的形状和分布。

% =========================================================================% =========================================================================      

% 1. **适用场景**：当前以`max_locs`为种子，适合分割**凸起的峰状形貌**；如果分析腐蚀凹坑，建议将输入换成`min_locs`，或将高程数据取反后再分割，更符合分水岭 “积水汇流” 的物理意义。
% 2. **关键调参**：
   % - `sigma`：越大边界越平滑，细节丢失越多；
   % - `yuzhi`：越大背景区域越大，边缘区域不参与分割；
   % - 局部梯度阈值系数`0.01`：越大越容易合并小区域，分割越粗略。

   % 简单理解（不同位置的sigma）：
   % 高斯平滑本质就是**给表面 “磨皮”**：
        %`sigma` 就是磨皮的力度，数值越大，磨得越狠；
        %磨完之后表面的小凸起、小凹坑、细碎噪点都会被磨平，但大的轮廓也会跟着变模糊。

% =========================================================================% =========================================================================       
   % 第一个：分水岭里的 sigma=0.5（轻磨皮）
   %这是**专门给 “画坑的边界” 用的**。|
    %画边界最怕两件事：
        % - 表面的小毛刺、扫描噪点太多，会被误当成 “坑边”，把一个完整的坑切成好几个碎块；
        % - 磨得太狠，坑的真实边缘就糊了，画出来的边界位置就不准了。
        %所以用很小的力度轻轻磨一下，只去掉最表层的细碎噪点，尽量保住坑的真实边缘，让分割出来的边界既不细碎，也不跑偏。
        % 而且这个轻磨只用来画边界，**不会改动你最终算深度的原始数据**。
% =========================================================================% =========================================================================       
    %第二个：主流程里的 sigma=2.0（重磨皮）
    %这是**专门给 “算深度、算面积” 用的**。
        %算定量数值最怕的是：表面密密麻麻的微小凹凸、扫描杂点会干扰结果，导致每次算出来的深度、面积都不一样，数据不稳。
        %所以用更大的力度整体磨一遍，把微观的小起伏都磨平，只留下大腐蚀坑的整体宏观形状。这样算出来的平均深度、总体积、总面积这些数值就会很稳定，重复性好。
        %这个重磨是直接改了原始网格数据，**后面所有计算、画图都用这个磨平后的版本**。

    %为什么要分两次磨？
    % 因为两个环节的需求刚好相反：

    % - 画边界要 “准”，不能磨太狠，不然轮廓就歪了；
    % - 算数值要 “稳”，不能磨太轻，不然小噪点会捣乱。

    % 所以就分开做：轻磨服务于画边界，重磨服务于算参数，各司其职。
