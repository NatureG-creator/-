function [boundaries,boundary_coords] = ...
    fenshuiling_boundry(surface_data, max_locs, yuzhi, cfg)
    if nargin < 4 || isempty(cfg)
        cfg = step00_corrosion_config();
    end
    if nargin < 3 || isempty(yuzhi)
        yuzhi = cfg.watershed.threshold;
    end
    %输入量：surface_data - 二维矩阵表示的三维高度数据 ，就是前面 `shujuguiyi` 输出的 `Z` 或 `Z_filled`；
    %输入量：max_locs：极大值点坐标，格式为 `[行号, 列号]`，作为分割的种子点，来自jixiantiqu；
    %输入量：yuzhi——分水岭分割阈值，控制边界识别的灵敏度，见untitled；
    %输出参数：boundaries：边界二值矩阵：和原图尺寸一致，边界位置为 1，区域内部为 0；
    %输出参数：boundary_coords：各区域边界三维坐标：元胞数组，每个元胞对应一个区域，存 `[x, y, 高程]` 格式的边界点
    
    % 初始化标记矩阵，生成和原图同尺寸的零矩阵，在每个极大值点的位置赋值为对应的序号`k`。
    % 作用：为分水岭算法指定**汇水种子点**，每个种子对应最终的一个分割区域，保证分割区域数量和极值点一一对应，避免过分割。
    markers = zeros(size(surface_data));
    for k = 1:size(max_locs,1)
        markers(max_locs(k,1), max_locs(k,2)) = k;
    end
    
    % 高斯平滑处理，对原始高程数据做高斯滤波平滑。
    % 作用：抑制表面的微小噪声与高频起伏，避免后续梯度计算产生大量伪边缘，让分割边界更平滑、更符合宏观形貌。
    sigma = cfg.watershed.gaussian_sigma;
    smoothed_data = imgaussfilt(surface_data, sigma);
    
    % 梯度计算与处理，用 Sobel 算子计算平滑后数据在 x、y 方向的梯度；
    % `hypot` 合成梯度幅值矩阵，反映表面的陡峭程度：边缘 / 陡坡处梯度大，平缓区域梯度小。
    % 分水岭算法本质是在**梯度图**上进行模拟积水扩张，梯度高的位置天然成为区域间的分水岭。
    [gx, gy] = imgradientxy( ...
        smoothed_data, cfg.watershed.gradient_operator);
    gradient_mag = hypot(gx, gy);
    
    % 自适应梯度阈值处理，`stdfilt` 计算 5×5 邻域内的局部标准差，表征局部对比度；
    % 对梯度小于局部阈值的平缓区域，强制将梯度值设为 255（高值屏障）。
    % 作用：避免平缓区域因梯度过小而出现细碎的过分割，将微小起伏合并到同一个大区域内，提升分割的整体性。
    contrast_window = cfg.watershed.local_contrast_window;
    local_contrast = stdfilt(surface_data, ones(contrast_window));
    min_height_diff = cfg.watershed.local_contrast_factor * local_contrast;
    gradient_mag(gradient_mag < min_height_diff) = ...
        cfg.watershed.gradient_barrier_value;
    
    % 背景标记检测，`bwdist` 对种子点做距离变换，得到每个像素到最近种子点的距离；
    % 距离大于 `yuzhi × 最大距离` 的外围区域判定为背景，统一标记为 255。
    % 作用：固定外围背景区域，防止分水岭算法将边缘背景分割成多个无意义区域；`yuzhi` 越大，背景范围越大，参与分割的有效区域越小。
    distance = bwdist(markers > 0);
    background = distance > yuzhi*max(distance(:));
    markers(background) = 255;
    
    % 梯度图修正，在所有标记点（种子点 + 背景点）位置，强制将梯度修正为局部最小值。
    % 这是**标记控制分水岭**的标准预处理步骤，保证每个种子点都是积水的最低点，分割只会从指定种子开始扩张，彻底避免无标记的过分割。
    gradient_modified = imimposemin(gradient_mag, markers > 0);
    
    % 分水岭分割，对修正后的梯度图执行分水岭算法，输出标签矩阵`labels`：
    % 每个独立区域对应一个唯一的整数标签；
    % 标签为 0 的像素，就是区域之间的分水岭边界线。
    labels = watershed(gradient_modified);
    
    % 建立极值点与区域的映射，逐一对每个极大值点做边界提取：
    % 1. 根据极值点坐标，获取它所在区域的标签；
    % 2. 生成该区域的二值掩码，`bwboundaries` 提取区域外轮廓（`noholes` 忽略内部孔洞边界）；
    % 3. 坐标转换：将边界的`[行,列]`转为`[x,y]`，并提取对应位置的高程值，拼接成`[x, y, 高程]`的三维边界坐标；
    % 4. 存入元胞数组，每个元胞对应一个区域的完整边界。
    boundary_coords = cell(size(max_locs,1), 1); % 按输入顺序初始化
    for k = 1:size(max_locs,1)
        % 获取当前极值点坐标
        r = max_locs(k,1);
        c = max_locs(k,2);
        
        % 验证坐标有效性
        if r > size(labels,1) || c > size(labels,2)
            warning('无效坐标: 索引%d (%d,%d)',k,r,c);
            continue;
        end
        
        % 获取对应区域标签
        region_label = labels(r,c);
        
        % 提取区域边界
        region_mask = (labels == region_label);
        B = bwboundaries(region_mask, cfg.watershed.boundary_holes);
        
        if ~isempty(B)
            % 转换为[x,y,height]格式
            coords = B{1}(:, [2 1]); 
            heights = surface_data(sub2ind(size(surface_data), coords(:,2), coords(:,1)));
            boundary_coords{k} = [coords, heights];
        else
            boundary_coords{k} = [];
            warning('未找到索引%d的边界',k);
        end
    end
    
    % 生成边界矩阵，分水岭标签为 0 的位置就是所有区域的公共边界，直接生成二值边界图。
    boundaries = labels == 0;
    
    % 可视化系统，生成 2×3 的子图面板，从原始数据、种子标记、梯度图、边界、区域标签、三维叠加六个维度直观展示分割效果，用于调参和结果验证。
    figure
    subplot(2,3,1), imshow(surface_data,[]), title('原始数据')
    subplot(2,3,2), imshow(markers>0), title('极值点标记')
    subplot(2,3,3), imshow(gradient_modified,[]), title('修正梯度')
    subplot(2,3,4), imshow(boundaries), title('分割边界')
    subplot(2,3,5), imshow(label2rgb(labels, ...
        cfg.figure.watershed_colormap, 'k')), title('区域标签')
    subplot(2,3,6), surf(smoothed_data,'EdgeColor','none'), hold on
    contour3(boundaries,[1 1],'r', ...
        'LineWidth', cfg.figure.boundary_line_width), ...
        view(cfg.figure.watershed_view), title('3D可视化')
end

% ### 1. 先插旗子（种子标记）
% 
% 在整个地面上，找到所有山顶（极大值点），每个山顶插一面带编号的旗子。
% 
% - 作用：提前说好就这几个山头，每个山头最终对应一块地盘，不会乱分出多余的小块。
% 
% ### 2. 轻轻抹平地面（高斯平滑）
% 
% 把地面上的小碎石、小土坑这些细碎的小起伏稍微抹平一点。
% 
% - 作用：不然后面算山坡陡缓的时候，这些小碎坑会被误当成 “小山脊”，把一个好好的山头拆成好几块。只轻轻抹一下，大的山坡形状基本不变。
% 
% ### 3. 算山坡陡缓（梯度计算）
% 
% 算出地面上每个点的陡峭程度：山坡越陡，数值越大；平地数值越小。
% 
% - 分水岭的核心逻辑就是：陡的地方留不住水，天然就是两个区域的分界线。
% 
% ### 4. 平地垒高墙（自适应梯度修正）
% 
% 在特别平的地方，人为把 “陡度” 拉满，修成一道高墙。
% 
% - 作用：平地本来水容易漫过去，会碎成好多小块。垒上墙之后，水就不会随便漫，小起伏都会被合并到一个大山头里，分出来的区域更完整。
% 
% ### 5. 圈出外围荒地（背景区域标记）
% 
% 从所有旗子往外量距离，最外圈很远的地方，统一圈成「背景荒地」，不算在任何山头里。
% 
% - 作用：防止边缘那些没意义的地方也被分成乱七八糟的小块。参数`yuzhi`就是控制圈多大的背景，数越大，圈进去的荒地越多，中间参与划分的有效区域越小。
% 
% ### 6. 保证旗子在最低处（强制梯度极小值）
% 
% 在所有插旗子的地方，还有圈出来的背景地方，强制把陡度改成最低。
% 
% - 作用：保证下雨的时候，水一定先从旗子那里开始积，然后慢慢往外涨，只会沿着旗子扩张，不会在别的地方莫名其妙冒出来一片水域，彻底避免乱分。
% 
% ### 7. 下雨涨水分地盘（分水岭分割）
% 
% 开始模拟下雨：水从每个旗子的位置慢慢往上涨，每个山头各自淹一片；水涨到两个区域碰在一起的地方，就停住，形成分界线。
% 
% - 最后给每块地盘编上号，所有分界线统一标成 0。
% 
% ### 8. 描出每个山头的边界（边界提取）
% 
% 挨个找到每个旗子对应的地盘，把它的外圈轮廓线描出来，再把线上每个点的高度也配上，变成「位置 + 高度」的完整边界线。
% 
% - 后面算深度、算面积、算体积，全靠这个边界线来算。
% 
% ### 9. 画出所有分界线（全局边界矩阵）
% 
% 把所有区域之间的分界线单独拎出来，做成一张黑白图，方便画图、验证效果。
% 
% ---
% 
% ### 最后那 6 张小图是干嘛的
% 
% 就是从**原始数据、旗子位置、陡度图、分界线、分块着色、三维立体**这 6 个角度，同时给你展示分得对不对，方便你调参数、看效果。
% 
% 补充一句：现在这个版本是按「山头（极大值）」来分的。如果你要分析的是腐蚀凹坑，更建议换成用坑底（极小值点）当种子，或者把表面上下反过来再分，更符合 “积水成坑” 的直觉。
