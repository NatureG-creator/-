"""Validate actual MAPDL diagnostics without certifying numerical/RST results.

The material history is an element nodal NL,EPEQ proxy. Its coordinates
are checked against the original eight-node mesh, never inferred from an
undeclared integration-point result. No report is generated by this reader.
"""
from __future__ import annotations

import copy
import hashlib
import json
from pathlib import Path

import numpy as np

from .apdl_diagnostics import material_coverage_hint, output_policy_summary
from .apdl_macros import DIAGNOSTICS_SCHEMA_VERSION


# Unscaled E19.11 writes 11 significant digits; allow its rounding error.
_MISO_COMPARISON_RTOL = 5.1e-11


def _json(path: Path) -> dict:
    def invalid(value):
        raise ValueError(f'非有限JSON值 {value}')
    try:
        value = json.loads(path.read_text(encoding='utf-8'), parse_constant=invalid)
        if not isinstance(value, dict):
            raise ValueError('必须是JSON对象')
        return value
    except (OSError, UnicodeError, ValueError) as exc:
        raise ValueError(f'无法读取 {path.name}：{exc}。') from exc


def _verified_file(output: Path, manifest: dict, name: str) -> Path:
    path = output/name
    hashes = manifest.get('files')
    if not isinstance(hashes, dict) or not isinstance(hashes.get(name), str):
        raise ValueError(f'manifest 缺少 {name} 的SHA256哈希。')
    try:
        digest = hashlib.sha256()
        with path.open('rb') as stream:
            for block in iter(lambda: stream.read(1024*1024), b''):
                digest.update(block)
    except OSError as exc:
        raise ValueError(f'无法核验输入文件 {name}：{exc}。') from exc
    if digest.hexdigest() != hashes[name]:
        raise ValueError(f'{name} 与manifest中的SHA256哈希不一致。')
    return path


def _csv(path: Path) -> np.ndarray:
    try:
        # Deliberately do not accept comment headers as np.loadtxt does.
        with path.open('r', encoding='utf-8-sig') as stream:
            rows = [line.strip().split(',') for line in stream if line.strip()]
        values = np.asarray(rows, dtype=float)
        if (values.ndim != 2 or values.shape[1] != 6 or not len(values)
                or not np.isfinite(values).all()):
            raise ValueError('必须是非空、有限的无表头6列数值CSV')
        return values
    except (OSError, UnicodeError, TypeError, ValueError) as exc:
        raise ValueError(f'{path.name} 无效：{exc}。') from exc


def _precheck(output: Path, stats: dict, options: dict) -> dict | None:
    path = output/'manifest.json'
    if not path.exists():
        return None
    manifest = _json(path)
    if 'diagnostics_schema_version' not in manifest:
        return None
    version = manifest['diagnostics_schema_version']
    if type(version) is not int or version != DIAGNOSTICS_SCHEMA_VERSION:
        raise ValueError(f'不支持或无效的 diagnostics schema 版本：{version!r}。')
    if manifest.get('options') != options or manifest.get('stats') != stats:
        raise ValueError('manifest 原始options/stats与本次结果验收输入不一致。')
    diagnostics = _json(_verified_file(output, manifest, 'diagnostics_precheck.json'))
    if (any(not isinstance(diagnostics.get(key), dict) for key in
            ('material_coverage', 'mesh_quality', 'output_policy'))
            or manifest.get('diagnostics') != diagnostics):
        raise ValueError('manifest 诊断对象与预检报告不一致。')
    if (diagnostics['material_coverage'] != material_coverage_hint(options)
            or diagnostics['output_policy'] != output_policy_summary(options)
            or manifest.get('output_policy') != diagnostics['output_policy']):
        raise ValueError('预检材料覆盖或保存策略与manifest原始参数不一致。')
    nodes = options['nx']*options['ny']*(options['layers']+1)
    elements = (options['nx']-1)*(options['ny']-1)*options['layers']
    quality = diagnostics['mesh_quality']
    if (stats['node_count'] != nodes or stats['element_count'] != elements
            or quality.get('node_count') != nodes or quality.get('element_count') != elements
            or quality.get('status') != 'precheck_only'):
        raise ValueError('manifest/预检节点和单元数量与网格参数不一致。')
    for name in ('nodes.dat', 'elements.dat'):
        _verified_file(output, manifest, name)
    return copy.deepcopy(diagnostics)


def _centroids(output: Path, ids: np.ndarray, nodes: np.ndarray, count: int) -> dict:
    """Stream EN commands and retain only elements used by the history."""
    wanted = set(map(int, ids))
    centers = {}
    node_ids = nodes[:, 0]
    try:
        with (output/'elements.dat').open('r', encoding='ascii') as stream:
            for line in stream:
                fields = line.strip().split(',')
                if len(fields) != 10 or fields[0].upper() != 'EN':
                    raise ValueError('elements.dat 不是 EN,id,n1,...,n8 格式')
                element_id = int(fields[1])
                if element_id not in wanted:
                    continue
                if element_id in centers or not 1 <= element_id <= count:
                    raise ValueError('原始单元编号重复或越界')
                references = np.asarray([int(value) for value in fields[2:]], dtype=np.int64)
                indices = np.searchsorted(node_ids, references)
                if (len(np.unique(references)) != 8 or np.any(indices >= len(node_ids))
                        or np.any(node_ids[indices] != references)):
                    raise ValueError('原始单元引用无效节点')
                centers[element_id] = (nodes[indices, 1:]/8).sum(axis=0)
        if set(centers) != wanted:
            raise ValueError('原始网格中缺少材料筛查引用单元')
    except (OSError, UnicodeError, OverflowError, ValueError) as exc:
        raise ValueError(f'material_coverage_history.csv 重心无法与实际输入网格核验：{exc}。') from exc
    return centers


def read_diagnostics_reports(output: Path, stats: dict, options: dict,
                             curve_times: np.ndarray, reference_nodes: np.ndarray | None) -> dict | None:
    """Return diagnostics/files/warnings for schema 2, None for legacy inputs.

    Actual stages/counts/pass flags are checked as an exact integer matrix.
    Original ANSYS quality text stays available for human review. No file
    can establish integration-point coverage or RST/CSV consistency here.
    """
    output = Path(output)
    diagnostics = _precheck(output, stats, options)
    if diagnostics is None:
        return None
    if reference_nodes is None:
        raise ValueError('新诊断schema需要可核验的原始 nodes.dat 网格。')
    if not np.array_equal(reference_nodes[:, 0], np.arange(1, stats['node_count']+1)):
        raise ValueError('新诊断schema原始网格节点必须使用连续编号。')
    grip = options['ny']*(options['layers']+1)
    expected = np.asarray([[1, stats['node_count'], stats['element_count'], -1, -1, 1],
                           [2, stats['node_count'], stats['element_count'], grip, grip, 1]])
    actual = _csv(output/'apdl_self_check.csv')
    if actual.shape != expected.shape or not np.array_equal(actual, expected):
        raise ValueError('apdl_self_check.csv 的阶段、节点/单元/端面数量或passed标志与预期不一致。')
    diagnostics['self_check'] = dict(state='passed', file='apdl_self_check.csv',
                                    stages=actual.astype(int).tolist(),
                                    note='实际导入网格与端面组件自检通过；不代表数值结果或RST验收通过。')
    report = output/'mesh_quality_report.txt'
    try:
        # Preserve raw text on disk; scan in bounded memory for non-whitespace.
        with report.open('r', encoding='utf-8', errors='replace') as stream:
            nonempty = any(line.strip() for line in stream)
        if not nonempty:
            raise ValueError('原始报告为空')
    except (OSError, ValueError) as exc:
        raise ValueError(f'mesh_quality_report.txt 无效：{exc}。') from exc
    quality_note = 'MAPDL原始CHECK/SHPP报告已保留，仍需人工审查；文件存在不代表网格质量通过。'
    diagnostics['mesh_quality']['native_report'] = dict(
        state='needs_review', file=report.name, note=quality_note)
    files = ['diagnostics_precheck.json', 'apdl_self_check.csv', report.name]
    warnings = [quality_note]
    for key in ('material_coverage', 'mesh_quality', 'output_policy'):
        warnings.extend(diagnostics[key].get('warnings', []))
    material = diagnostics['material_coverage']
    note = 'NL,EPEQ的元素节点最大值仅为筛查代理；末点附近的边界点仍需复核，未提示超表也不能保证全部积分点均在材料曲线覆盖内。'
    if options['material_model'] != 'multilinear_iso':
        material['screening'] = dict(state='not_applicable', note='弹性或BISO没有有限MISO表末点上界。')
    else:
        name = 'material_coverage_history.csv'
        history = _csv(output/name)
        times, plastic, element_ids = history[:, :3].T
        if (len(times) != len(curve_times) or np.any(np.diff(times) <= 0)
                or np.any(times < 0) or np.any(times > 1+1e-10)
                or not np.allclose(times, curve_times, rtol=5.1e-11, atol=1e-12)):
            raise ValueError(f'{name} 时间必须严格递增且逐结果集与force_displacement.csv对应。')
        if (np.any(plastic < 0) or np.any(element_ids != np.floor(element_ids))
                or np.any(element_ids < 1) or np.any(element_ids > stats['element_count'])):
            raise ValueError(f'{name} 塑性应变或单元整数编号无效/越界。')
        centers = _centroids(output, element_ids, reference_nodes, int(stats['element_count']))
        for row in history:
            if not np.allclose(row[3:], centers[int(row[2])], rtol=5.1e-11, atol=1e-10):
                raise ValueError(f'{name} 单元重心坐标与实际输入网格不一致，超出E19.11导出精度容差。')
        last = float(material['last_plastic_strain'])
        # Positive MISO endpoint: use a relative allowance without a fixed
        # absolute floor, and subtract to avoid overflowing last + allowance.
        difference = plastic-last
        allowance = last*_MISO_COMPARISON_RTOL
        flagged = np.flatnonzero(difference > allowance)
        near_limit_count = int(np.count_nonzero(np.abs(difference) <= allowance))
        comparison_note = ('按无1P缩放的E19.11导出精度，以MISO末点的5.1e-11相对容差比较，不使用固定绝对容差；'
                           '仅超出此容差才提示明确超表，容差内末点附近的边界点仍需复核。')
        first = history[flagged[0]] if len(flagged) else None
        material['screening'] = dict(
            state='flagged' if first is not None else 'no_flag', file=name,
            point_count=len(history), max_element_nodal_epeq=float(plastic.max()),
            near_limit_point_count=near_limit_count,
            comparison_relative_tolerance=_MISO_COMPARISON_RTOL, comparison_note=comparison_note,
            last_plastic_strain=last, centroid_verified=True,
            first_flag=(dict(time=float(first[0]), element_id=int(first[2]),
                             centroid_mm=first[3:].tolist()) if first is not None else None), note=note)
        if first is not None:
            warnings.append('材料覆盖筛查提示：元素节点NL,EPEQ代理超过MISO末塑性应变，请复核材料范围与热点。')
        if near_limit_count:
            warnings.append(comparison_note)
        warnings.append(note)
        files.append(name)
    return dict(diagnostics=diagnostics, warnings=list(dict.fromkeys(warnings)), files=files)
