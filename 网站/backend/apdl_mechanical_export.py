"""Export a frozen APDL/LS-DYNA mesh for Ansys Mechanical import."""
from __future__ import annotations

import json
import math
import os
import shutil
import subprocess
import zipfile
from pathlib import Path

import numpy as np


def _safe_options(spec):
    options = spec.get('options') or {}
    curve = options.get('plastic_curve') or []
    return options, curve


def _apdl_text(nodes, elements, options, fixed, loaded):
    curve = options.get('plastic_curve') or []
    axis = 1 if options.get('tensile_direction', 'X') == 'X' else 2
    lines = [
        '/CLEAR,NOSTART', '/PREP7',
        '! Generated by Corrosion Research Workbench',
        '! Units: N, mm, MPa, s, tonne',
        'ET,1,185',
        f'MP,EX,1,{float(options.get("E_MPa", 206000)):.12g}',
        f'MP,PRXY,1,{float(options.get("poisson_ratio", .3)):.12g}',
        f'MP,DENS,1,{float(options.get("density_tonne_mm3", 7.85e-9)):.12g}',
    ]
    if curve:
        lines += [f'TB,MISO,1,,,{len(curve)}', 'TBTEMP,0']
        lines += [f'TBPT,,{float(strain):.12g},{float(stress):.12g}' for strain, stress in curve]
    lines.append('TYPE,1')
    lines += [f'N,{int(row[0])},{row[1]:.12g},{row[2]:.12g},{row[3]:.12g}' for row in nodes]
    lines += [f'E,{int(row[1])},{int(row[2])},{int(row[3])},{int(row[4])},{int(row[5])},{int(row[6])},{int(row[7])},{int(row[8])}' for row in elements]
    lines += ['! Fixed and loaded node components used by the source tensile model', 'NSEL,NONE']
    lines += [f'NSEL,A,NODE,,{int(node)}' for node in fixed]
    lines += ['CM,MECH_FIXED,NODE', 'D,ALL,ALL,0', 'ALLSEL,ALL', 'NSEL,NONE']
    lines += [f'NSEL,A,NODE,,{int(node)}' for node in loaded]
    lines += ['CM,MECH_LOADED,NODE', f'D,ALL,{axis},0,{float(options.get("target_displacement_mm", 0)):.12g}', 'ALLSEL,ALL', '/SOLU',
              'ANTYPE,STATIC', 'NLGEOM,ON', 'OUTRES,ALL,ALL', 'SAVE', '/PREP7',
              'CDWRITE,DB,mechanical_model,CDB',
              'FINISH', '/EXIT,NOSAVE', '']
    return '\n'.join(lines)


def _step_text(nodes, elements):
    """Write a faceted AP214 BREP from exposed hex faces.

    This is geometry-only: no material, mesh, loads, damage, or results are
    encoded in STEP. The mesh boundary is converted to triangular facets.
    """
    faces = {}
    for row in elements:
        ids = [int(v) for v in row[1:9]]
        quads = ((ids[0], ids[1], ids[2], ids[3]), (ids[4], ids[7], ids[6], ids[5]),
                 (ids[0], ids[4], ids[5], ids[1]), (ids[1], ids[5], ids[6], ids[2]),
                 (ids[2], ids[6], ids[7], ids[3]), (ids[4], ids[0], ids[3], ids[7]))
        for face in quads:
            key = tuple(sorted(face))
            if key in faces:
                del faces[key]
            else:
                faces[key] = face
    point_id = {}
    entities = []
    next_id = 10
    for row in nodes:
        point_id[int(row[0])] = next_id
        entities.append((next_id, f"CARTESIAN_POINT('',({row[1]:.12g},{row[2]:.12g},{row[3]:.12g}))"))
        next_id += 1
    face_ids = []
    for face in faces.values():
        for tri in ((face[0], face[1], face[2]), (face[0], face[2], face[3])):
            p1, p2, p3 = (point_id[v] for v in tri)
            origin = next_id; entities.append((origin, f"CARTESIAN_POINT('',({nodes[p1-10,1]:.12g},{nodes[p1-10,2]:.12g},{nodes[p1-10,3]:.12g}))")); next_id += 1
            d1 = next_id; entities.append((d1, "DIRECTION('',(0.,0.,1.))")); next_id += 1
            d2 = next_id; entities.append((d2, "DIRECTION('',(1.,0.,0.))")); next_id += 1
            axis = next_id; entities.append((axis, f"AXIS2_PLACEMENT_3D('',#{origin},#{d1},#{d2})")); next_id += 1
            plane = next_id; entities.append((plane, f"PLANE('',#{axis})")); next_id += 1
            loop = next_id; entities.append((loop, f"POLY_LOOP('',(#{p1},#{p2},#{p3}))")); next_id += 1
            bound = next_id; entities.append((bound, f"FACE_OUTER_BOUND('',#{loop},.T.)")); next_id += 1
            face_id = next_id; entities.append((face_id, f"ADVANCED_FACE('',(#{bound}),#{plane},.T.)")); next_id += 1
            face_ids.append(face_id)
    shell = next_id; entities.append((shell, "CLOSED_SHELL('',(" + ','.join(f'#{v}' for v in face_ids) + '))')); next_id += 1
    brep = next_id; entities.append((brep, f"FACETED_BREP('Corrosion specimen',#{shell})"))
    body = '\n'.join(f'#{i}={text};' for i, text in entities)
    return "ISO-10303-21;\nHEADER;\nFILE_DESCRIPTION(('Corrosion Workbench faceted geometry'),'2;1');\nFILE_NAME('mechanical_model.step','2026-10-28',('Corrosion Workbench'),('OpenAI'),'','Ansys Mechanical','');\nFILE_SCHEMA(('AUTOMOTIVE_DESIGN_CC2'));\nENDSEC;\nDATA;\n" + body + "\nENDSEC;\nEND-ISO-10303-21;\n"


def export_mechanical_model(service, job_id):
    service.validate_id(job_id)
    job_dir = service.runtime / 'jobs' / job_id
    status = service.get_job(job_id)
    if status.get('kind') != 'apdl_tension' or status.get('state') != 'completed':
        raise ValueError('只有已完成的 APDL/LS-DYNA 拉伸任务可以导出 Mechanical 模型')
    output = job_dir / 'outputs'
    geometry_path = output / 'fracture_geometry.npz'
    if not geometry_path.is_file():
        raise ValueError('任务没有冻结网格 fracture_geometry.npz，无法导出')
    spec = json.loads((job_dir / 'spec.json').read_text(encoding='utf-8'))
    with np.load(geometry_path, allow_pickle=False) as saved:
        nodes = saved['nodes']; elements = saved['elements']; fixed = saved['fixed']; loaded = saved['loaded']
    export_dir = output / 'mechanical_export'
    export_dir.mkdir(exist_ok=True)
    inp = export_dir / 'mechanical_model.inp'
    step = export_dir / 'mechanical_model.step'
    report = export_dir / 'mechanical_export_report.json'
    options, _ = _safe_options(spec)
    inp.write_text(_apdl_text(nodes, elements, options, fixed, loaded), encoding='ascii')
    step.write_text(_step_text(nodes, elements), encoding='ascii')
    cdb = export_dir / 'mechanical_model.cdb'
    cdb_status = 'not_generated'
    mapdl = os.environ.get('MAPDL_BIN') or r'C:\Program Files\ANSYS Inc\v252\ansys\bin\winx64\ANSYS252.exe'
    if mapdl and Path(mapdl).is_file():
        command = [mapdl, '-b', '-i', inp.name, '-o', 'mechanical_export.out', '-j', 'mechanical_export']
        try:
            subprocess.run(command, cwd=export_dir, check=True, timeout=120,
                           creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
            archive = next((p for p in export_dir.iterdir() if p.name.lower() == 'mechanical_model.cdb'), None)
            if archive is not None and archive != cdb:
                shutil.copy2(archive, cdb)
            cdb_status = 'generated' if cdb.is_file() else 'mapdl_finished_without_cdb'
        except (OSError, subprocess.SubprocessError) as exc:
            cdb_status = f'failed:{type(exc).__name__}'
    payload = {
        'schema_version': 1, 'job_id': job_id, 'node_count': int(len(nodes)),
        'element_count': int(len(elements)), 'mesh_type': spec.get('options', {}).get('mesh_type'),
        'files': ['mechanical_model.inp', 'mechanical_model.step'] + (['mechanical_model.cdb'] if cdb.is_file() else []),
        'cdb_status': cdb_status,
        'inp_note': 'APDL command stream; run in MAPDL or Mechanical Command Snippet. It contains mesh, MISO material, node components, constraints and displacement load.',
        'step_note': 'Faceted geometry only; STEP contains no mesh, material, boundary, damage or result data.',
    }
    report.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding='utf-8')
    archive = output / 'ansys_mechanical_model_bundle.zip'
    with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as z:
        for name in payload['files'] + ['mechanical_export_report.json']:
            z.write(export_dir / name, name)
    files = [f'mechanical_export/{name}' for name in payload['files'] + ['mechanical_export_report.json']] + ['ansys_mechanical_model_bundle.zip']
    return dict(job_id=job_id, node_count=int(len(nodes)), element_count=int(len(elements)),
                cdb_status=cdb_status, files=files,
                note='STEP 仅几何；INP/CDB 才包含网格和材料/边界命令。')
