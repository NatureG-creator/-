"""第六步：把 Python 结果导出为 MATLAB 可直接出图的数据。

功能：
- 自动读取 `腐蚀综合代码` 的 `.npz` 结果文件；
- 导出 MATLAB `untitled.m` 出图所需变量：
  `a_output`、`d_output`、`cl_output`、`perfect_result`、`perfect_parameter`、
  `w`、`l`、`n`、`space`；
- 额外生成一个 MATLAB 脚本 `run_python_export_matlab_figures.m`，
  可直接复刻 `untitled.m` 的出图/分布检验流程。

使用：
    .\\.venv\\Scripts\\python.exe .\\腐蚀综合代码\\06_导出MATLAB出图数据.py
"""

